-- Oracle Database 21c XE manual schema script for Resource Service.
-- Review src/main/resources/db/README.md and inspect the target schema before running.
-- This script contains no DROP, TRUNCATE, ALTER, or UPDATE statements.
-- Existing VEHICLES and VEHICLE_SEQ are intentionally not targeted by any DDL.
-- Run manually using SQL Developer or SQL*Plus; this file is not auto-run by Spring Boot.

SET SERVEROUTPUT ON

DECLARE
    v_count NUMBER;
    v_max_id NUMBER;
    v_start NUMBER;
BEGIN
    -- PERSONNEL: create only when absent. If it already exists, no table changes are made.
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'PERSONNEL';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE PERSONNEL (
            PERSONNEL_ID NUMBER(19) NOT NULL,
            PERSONNEL_CODE VARCHAR2(30) NOT NULL,
            FULL_NAME VARCHAR2(100) NOT NULL,
            ROLE VARCHAR2(50) NOT NULL,
            UNIT_ID NUMBER(19) NOT NULL,
            POSTING_LOCATION VARCHAR2(100),
            AVAILABILITY VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
            ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
            CREATED_AT TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP NOT NULL,
            CONSTRAINT PK_PERSONNEL PRIMARY KEY (PERSONNEL_ID),
            CONSTRAINT CK_PERSONNEL_UNIT CHECK (UNIT_ID > 0),
            CONSTRAINT CK_PERSONNEL_ACTIVE CHECK (ACTIVE IN (0, 1))
        )~';
        DBMS_OUTPUT.PUT_LINE('Created PERSONNEL');
    ELSE
        DBMS_OUTPUT.PUT_LINE('PERSONNEL exists; skipped');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'UX_PERSONNEL_CODE_UPPER';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_PERSONNEL_CODE_UPPER ON PERSONNEL (UPPER(PERSONNEL_CODE))';
    END IF;

    -- Use a start value above existing IDs when the sequence is absent and table exists.
    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'PERSONNEL_SEQ';
    IF v_count = 0 THEN
        v_max_id := 0;
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'PERSONNEL';
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(PERSONNEL_ID), 0) FROM PERSONNEL' INTO v_max_id;
        END IF;
        v_start := v_max_id + 1;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE PERSONNEL_SEQ START WITH ' || TO_CHAR(v_start, 'FM9999999999999999990') || ' INCREMENT BY 1 NOCACHE NOCYCLE';
        DBMS_OUTPUT.PUT_LINE('Created PERSONNEL_SEQ starting above existing IDs');
    ELSE
        DBMS_OUTPUT.PUT_LINE('PERSONNEL_SEQ exists; skipped without resetting');
    END IF;

    -- ASSETS
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'ASSETS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE ASSETS (
            ASSET_ID NUMBER(19) NOT NULL,
            ASSET_TAG VARCHAR2(50) NOT NULL,
            ASSET_NAME VARCHAR2(100) NOT NULL,
            CATEGORY VARCHAR2(50) NOT NULL,
            UNIT_ID NUMBER(19) NOT NULL,
            LOCATION VARCHAR2(100) NOT NULL,
            CONDITION_STATUS VARCHAR2(30) NOT NULL,
            STATUS VARCHAR2(30) NOT NULL,
            CREATED_AT TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP NOT NULL,
            CONSTRAINT PK_ASSETS PRIMARY KEY (ASSET_ID),
            CONSTRAINT CK_ASSETS_UNIT CHECK (UNIT_ID > 0)
        )~';
        DBMS_OUTPUT.PUT_LINE('Created ASSETS');
    ELSE
        DBMS_OUTPUT.PUT_LINE('ASSETS exists; skipped');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'UX_ASSETS_TAG_UPPER';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_ASSETS_TAG_UPPER ON ASSETS (UPPER(ASSET_TAG))';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'ASSET_SEQ';
    IF v_count = 0 THEN
        v_max_id := 0;
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'ASSETS';
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(ASSET_ID), 0) FROM ASSETS' INTO v_max_id;
        END IF;
        v_start := v_max_id + 1;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE ASSET_SEQ START WITH ' || TO_CHAR(v_start, 'FM9999999999999999990') || ' INCREMENT BY 1 NOCACHE NOCYCLE';
        DBMS_OUTPUT.PUT_LINE('Created ASSET_SEQ starting above existing IDs');
    ELSE
        DBMS_OUTPUT.PUT_LINE('ASSET_SEQ exists; skipped without resetting');
    END IF;

    -- INVENTORY_ITEMS
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'INVENTORY_ITEMS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE INVENTORY_ITEMS (
            ITEM_ID NUMBER(19) NOT NULL,
            ITEM_CODE VARCHAR2(50) NOT NULL,
            ITEM_NAME VARCHAR2(100) NOT NULL,
            CATEGORY VARCHAR2(50) NOT NULL,
            UNIT_OF_MEASURE VARCHAR2(30) NOT NULL,
            UNIT_ID NUMBER(19) NOT NULL,
            LOCATION VARCHAR2(100) NOT NULL,
            QUANTITY_ON_HAND NUMBER(19,4) DEFAULT 0 NOT NULL,
            QUANTITY_RESERVED NUMBER(19,4) DEFAULT 0 NOT NULL,
            REORDER_THRESHOLD NUMBER(19,4) DEFAULT 0 NOT NULL,
            CREATED_AT TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP NOT NULL,
            CONSTRAINT PK_INVENTORY_ITEMS PRIMARY KEY (ITEM_ID),
            CONSTRAINT CK_INV_ITEM_UNIT CHECK (UNIT_ID > 0),
            CONSTRAINT CK_INV_ITEM_ON_HAND CHECK (QUANTITY_ON_HAND >= 0),
            CONSTRAINT CK_INV_ITEM_RESERVED CHECK (QUANTITY_RESERVED >= 0 AND QUANTITY_RESERVED <= QUANTITY_ON_HAND),
            CONSTRAINT CK_INV_ITEM_REORDER CHECK (REORDER_THRESHOLD >= 0)
        )~';
        DBMS_OUTPUT.PUT_LINE('Created INVENTORY_ITEMS');
    ELSE
        DBMS_OUTPUT.PUT_LINE('INVENTORY_ITEMS exists; skipped');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'UX_INV_ITEM_CODE_UPPER';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_INV_ITEM_CODE_UPPER ON INVENTORY_ITEMS (UPPER(ITEM_CODE))';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'INVENTORY_ITEM_SEQ';
    IF v_count = 0 THEN
        v_max_id := 0;
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'INVENTORY_ITEMS';
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(ITEM_ID), 0) FROM INVENTORY_ITEMS' INTO v_max_id;
        END IF;
        v_start := v_max_id + 1;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE INVENTORY_ITEM_SEQ START WITH ' || TO_CHAR(v_start, 'FM9999999999999999990') || ' INCREMENT BY 1 NOCACHE NOCYCLE';
        DBMS_OUTPUT.PUT_LINE('Created INVENTORY_ITEM_SEQ starting above existing IDs');
    ELSE
        DBMS_OUTPUT.PUT_LINE('INVENTORY_ITEM_SEQ exists; skipped without resetting');
    END IF;

    -- INVENTORY_TRANSACTIONS; retain history with a non-cascading FK.
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'INVENTORY_TRANSACTIONS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE INVENTORY_TRANSACTIONS (
            TRANSACTION_ID NUMBER(19) NOT NULL,
            ITEM_ID NUMBER(19) NOT NULL,
            TRANSACTION_TYPE VARCHAR2(20) NOT NULL,
            QUANTITY NUMBER(19,4) NOT NULL,
            REASON VARCHAR2(500) NOT NULL,
            CREATED_AT TIMESTAMP NOT NULL,
            CONSTRAINT PK_INV_TRANSACTIONS PRIMARY KEY (TRANSACTION_ID),
            CONSTRAINT FK_INV_TX_ITEM FOREIGN KEY (ITEM_ID) REFERENCES INVENTORY_ITEMS (ITEM_ID),
            CONSTRAINT CK_INV_TX_TYPE CHECK (TRANSACTION_TYPE IN ('RECEIVE', 'ISSUE', 'ADJUST')),
            CONSTRAINT CK_INV_TX_QTY CHECK (QUANTITY > 0)
        )~';
        DBMS_OUTPUT.PUT_LINE('Created INVENTORY_TRANSACTIONS');
    ELSE
        DBMS_OUTPUT.PUT_LINE('INVENTORY_TRANSACTIONS exists; skipped');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'INVENTORY_TRANSACTION_SEQ';
    IF v_count = 0 THEN
        v_max_id := 0;
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'INVENTORY_TRANSACTIONS';
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(TRANSACTION_ID), 0) FROM INVENTORY_TRANSACTIONS' INTO v_max_id;
        END IF;
        v_start := v_max_id + 1;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE INVENTORY_TRANSACTION_SEQ START WITH ' || TO_CHAR(v_start, 'FM9999999999999999990') || ' INCREMENT BY 1 NOCACHE NOCYCLE';
        DBMS_OUTPUT.PUT_LINE('Created INVENTORY_TRANSACTION_SEQ starting above existing IDs');
    ELSE
        DBMS_OUTPUT.PUT_LINE('INVENTORY_TRANSACTION_SEQ exists; skipped without resetting');
    END IF;

    -- Indexes support existing inventory history repository queries.
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_INV_TX_ITEM_CREATED';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_INV_TX_ITEM_CREATED ON INVENTORY_TRANSACTIONS (ITEM_ID, CREATED_AT DESC)';
    END IF;

    -- MAINTENANCE_RECORDS; resource references are polymorphic, so no resource FK is created.
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'MAINTENANCE_RECORDS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE MAINTENANCE_RECORDS (
            MAINTENANCE_ID NUMBER(19) NOT NULL,
            RESOURCE_TYPE VARCHAR2(30) NOT NULL,
            RESOURCE_ID NUMBER(19) NOT NULL,
            MAINTENANCE_TYPE VARCHAR2(50) NOT NULL,
            DESCRIPTION VARCHAR2(1000) NOT NULL,
            SCHEDULED_DATE TIMESTAMP NOT NULL,
            START_DATE TIMESTAMP,
            COMPLETION_DATE TIMESTAMP,
            STATUS VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
            SERVICE_NOTES VARCHAR2(2000),
            TECHNICIAN VARCHAR2(100),
            CREATED_AT TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP NOT NULL,
            CONSTRAINT PK_MAINTENANCE_RECORDS PRIMARY KEY (MAINTENANCE_ID),
            CONSTRAINT CK_MAINT_RESOURCE_ID CHECK (RESOURCE_ID > 0),
            CONSTRAINT CK_MAINT_STATUS CHECK (STATUS IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
            CONSTRAINT CK_MAINT_DATE_ORDER CHECK (COMPLETION_DATE IS NULL OR START_DATE IS NULL OR COMPLETION_DATE >= START_DATE)
        )~';
        DBMS_OUTPUT.PUT_LINE('Created MAINTENANCE_RECORDS');
    ELSE
        DBMS_OUTPUT.PUT_LINE('MAINTENANCE_RECORDS exists; skipped');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'MAINTENANCE_SEQ';
    IF v_count = 0 THEN
        v_max_id := 0;
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'MAINTENANCE_RECORDS';
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(MAINTENANCE_ID), 0) FROM MAINTENANCE_RECORDS' INTO v_max_id;
        END IF;
        v_start := v_max_id + 1;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE MAINTENANCE_SEQ START WITH ' || TO_CHAR(v_start, 'FM9999999999999999990') || ' INCREMENT BY 1 NOCACHE NOCYCLE';
        DBMS_OUTPUT.PUT_LINE('Created MAINTENANCE_SEQ starting above existing IDs');
    ELSE
        DBMS_OUTPUT.PUT_LINE('MAINTENANCE_SEQ exists; skipped without resetting');
    END IF;

    -- Indexes support repository filters and date-ordered maintenance queries.
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_MAINT_RESOURCE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_MAINT_RESOURCE ON MAINTENANCE_RECORDS (LOWER(RESOURCE_TYPE), RESOURCE_ID)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_MAINT_STATUS_DATE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_MAINT_STATUS_DATE ON MAINTENANCE_RECORDS (UPPER(STATUS), SCHEDULED_DATE)';
    END IF;

    DBMS_OUTPUT.PUT_LINE('Schema script completed. Existing objects were skipped; no data was deleted.');
END;
